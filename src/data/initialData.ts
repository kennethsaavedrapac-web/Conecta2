// Helper to generate ISO strings offset by days and hours from now
export function getDateOffset(daysAgo: number, hour: number = 10, minute: number = 30): string {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

